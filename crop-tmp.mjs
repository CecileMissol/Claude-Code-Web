import { chromium } from '@playwright/test';
import { readFileSync } from 'node:fs';
const [file, x, y, w, h, scale] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const s = Number(scale ?? 3);
const p = await b.newPage({ viewport: { width: Number(w) * s, height: Number(h) * s } });
const data = readFileSync(file).toString('base64');
await p.setContent(`<body style="margin:0;background:#fff"><div style="width:${Number(w)*s}px;height:${Number(h)*s}px;overflow:hidden;position:relative"><img src="data:image/png;base64,${data}" style="position:absolute;left:${-x*s}px;top:${-y*s}px;width:auto;transform-origin:0 0;transform:scale(${s})"></div></body>`);
await p.waitForTimeout(300);
await p.screenshot({ path: '/tmp/claude-0/crop.png' });
await b.close();
